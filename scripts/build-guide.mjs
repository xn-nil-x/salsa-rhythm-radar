/**
 * Build the self-contained HTML user guide.
 *
 *   npm run guide
 *
 * Reads docs/user-guide.src.html (images referenced as img/*.png|svg),
 * embeds every image as a data: URI and rewrites links to other repository
 * documents into absolute GitHub URLs, so docs/user-guide.html works as a
 * single file: opened offline, attached to an e-mail, or put on any server.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const docs = join(root, 'docs');
const SRC = join(docs, 'user-guide.src.html');
const OUT = join(docs, 'user-guide.html');
const REPO = 'https://github.com/xn-nil-x/salsa-rhythm-radar/blob/main';
const MIME = { png: 'image/png', svg: 'image/svg+xml', jpg: 'image/jpeg', webp: 'image/webp' };

let html = readFileSync(SRC, 'utf8');
const missing = [];
let embedded = 0;

// <img src="..."> and <link rel="icon" href="..."> pointing to local files.
html = html.replace(/\b(src|href)="((?:\.\.\/)?(?:img|public)\/[^"]+\.(png|svg|jpg|webp))"/g, (_m, attr, path, ext) => {
  const file = resolve(docs, path);
  if (!existsSync(file)) {
    missing.push(path);
    return `${attr}="${path}"`;
  }
  embedded++;
  const data = readFileSync(file).toString('base64');
  return `${attr}="data:${MIME[ext]};base64,${data}"`;
});

// Links to repository documents: make them absolute so they work outside the repo.
html = html.replace(/href="(\.\.\/)?([A-Za-z_][\w.-]*\.md)(#[^"]*)?"/g, (_m, up, file, hash = '') => {
  const path = up ? file : `docs/${file}`;
  return `href="${REPO}/${path}${hash}"`;
});

html = html.replace('<!doctype html>', '<!doctype html>\n<!-- Generated by scripts/build-guide.mjs from docs/user-guide.src.html — edit the source, then run `npm run guide`. -->');

if (missing.length) {
  console.error('Missing images:', missing.join(', '));
  process.exit(1);
}
writeFileSync(OUT, html);
console.log(`docs/user-guide.html: ${embedded} images embedded, ${(Buffer.byteLength(html) / 1048576).toFixed(1)} MB`);
